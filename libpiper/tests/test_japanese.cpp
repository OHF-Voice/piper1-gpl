// Golden parity tests for the Japanese phonemizer.
//
// The ja_JA voice was trained on the output of piper/phonemize_japanese.py, so
// the C++ port must produce identical phoneme sequences. Expected values below
// were generated with pyopenjtalk-plus (the `ja` training extra) via:
//
//   python3 gen_japanese_golden.py
//
// and pasted here. If the Python output ever changes, regenerate.

