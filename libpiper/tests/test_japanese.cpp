// phonemize() returns one UTF-8 string per sentence, each a concatenation of
// single-codepoint phonemes. Re-split into space-separated codepoints so the
// golden vectors stay readable.
std::string spaced(const std::string &s) {
  std::string out;
  for (size_t i = 0; i < s.size();) {
    unsigned char c = static_cast<unsigned char>(s[i]);
    size_t n = 1;
    if ((c & 0x80) == 0)
      n = 1;
    else if ((c & 0xE0) == 0xC0)
      n = 2;
    else if ((c & 0xF0) == 0xE0)
      n = 3;
    else if ((c & 0xF8) == 0xF0)
      n = 4;
    if (i + n > s.size())
      n = s.size() - i;
    if (!out.empty())
      out.push_back(' ');
    out.append(s, i, n);
    i += n;
  }
  return out;
}

// splitSentences needs no dictionary.
TEST(JapaneseSplitSentences, Basic) {
  auto s = JapanesePhonemizer::splitSentences(
      "今日は良い天気です。明日も晴れるでしょう。");
  ASSERT_EQ(s.size(), 2u);
  EXPECT_EQ(s[0], "今日は良い天気です。");
  EXPECT_EQ(s[1], "明日も晴れるでしょう。");
}

TEST(JapaneseSplitSentences, DecimalGuard) {
  // The "." in "1.5" is not a sentence boundary.
  auto s = JapanesePhonemizer::splitSentences("1.5リットルください。");
  ASSERT_EQ(s.size(), 1u);
  EXPECT_EQ(s[0], "1.5リットルください。");
}

TEST(JapaneseSplitSentences, TrailingClosers) {
  auto s = JapanesePhonemizer::splitSentences("「行きます」と言った。そうだ。");
  ASSERT_EQ(s.size(), 2u);
  EXPECT_EQ(s[0], "「行きます」と言った。");
  EXPECT_EQ(s[1], "そうだ。");
}

TEST(JapaneseSplitSentences, NoFinalPunctuation) {
  auto s = JapanesePhonemizer::splitSentences("おはようございます");
  ASSERT_EQ(s.size(), 1u);
  EXPECT_EQ(s[0], "おはようございます");
}

TEST(JapaneseSplitSentences, QuestionAndExclamation) {
  auto s = JapanesePhonemizer::splitSentences("元気ですか？はい！");
  ASSERT_EQ(s.size(), 2u);
  EXPECT_EQ(s[0], "元気ですか？");
  EXPECT_EQ(s[1], "はい！");
}

// Full phonemize() tests need the OpenJTalk dictionary. Point
// OPENJTALK_TEST_DICT_DIR at the pyopenjtalk-plus dictionary directory
// (the one containing sys.dic); otherwise the tests skip.
class JapaneseGoldenTest : public ::testing::Test {
protected:
  void SetUp() override {
    const char *dict_dir = std::getenv("OPENJTALK_TEST_DICT_DIR");
    if (dict_dir == nullptr || dict_dir[0] == '\0') {
      GTEST_SKIP() << "OPENJTALK_TEST_DICT_DIR not set; skipping golden test. "
                      "Point it at the pyopenjtalk-plus dictionary to run.";
    }
    ASSERT_TRUE(phonemizer_.load(dict_dir)) << "failed to load " << dict_dir;
  }

  JapanesePhonemizer phonemizer_;
};

// Each case: {input sentence, expected IPA+prosody phonemes, space-separated}.
// Expected strings were generated by the Python training-time phonemizer.
TEST_F(JapaneseGoldenTest, GoldenVectors) {
  const std::vector<std::pair<std::string, std::string>> cases = {
      // Basic: kanji readings, は particle -> わ, accent phrase boundary.
      {"今日は良い天気です。",
       "k ʲ o ↓ o w a # j o ↓ i # t e ↓ ɴ k i d e s ɯ ."},
      // Decimal guard + katakana loanwords + geminate っ -> ʔ.
      {"これは1.5リットルのペットボトルです。",
       "k o ↑ ɾ e w a # i ↓ ʔ t e ɴ # ɡ o ↑ ɾ i ↓ ʔ t o ɾ ɯ n o # p e ↑ ʔ t o "
       "b o ↓ t o ɾ ɯ d e s ɯ ."},
      // Question intonation (e3 == 1 -> ?).
      {"元気ですか？", "ɡ e ↓ ɴ k i d e s ɯ k a ?"},
      // Causative/passive verb chaining (F2@1 rule).
      {"食べさせられたくなかった。",
       "t a ↑ b e s a s e ɾ a ↓ ɾ e t a k ɯ n a k a ʔ t a ."},
      // Fraction denominator: 分 -> ブン.
      {"三分の二は小数で表せます。",
       "s a ↓ ɴ b ɯ ɴ n o # n i ↓ w a # ɕ o ↑ o s ɯ ↓ ɯ d e # a ↑ ɾ a w a s e m "
       "a ↓ s ɯ ."},
      // Rendaku rule: 不足 -> ブソク after a noun.
      {"情報が不足する場合は連絡してください。",
       "d ʑ o ↑ o h o o ɡ a # ɸ ɯ ↑ s o k ɯ s ɯ ɾ ɯ # b a ↑ a i w a # ɾ e ↑ ɴ "
       "ɾ a k ɯ ɕ i t e k ɯ d a s a ↓ i ."},
      // 球 suffix rule (キュウ, not ダマ, without okurigana mix).
      {"野球の球を投げた。", "j a ↑ k ʲ ɯ ɯ n o # t a ↓ m a o # n a ↓ ɡ e t a ."},
      // Devoiced vowel folding: です -> desu.
      {"おはようございます。", "o ↑ h a j o o # ɡ o ↑ z a i m a ↓ s ɯ ."},
  };
  for (const auto &[input, expected] : cases) {
    auto sentences = phonemizer_.phonemize(input);
    ASSERT_EQ(sentences.size(), 1u) << "input: " << input;
    EXPECT_EQ(spaced(sentences[0]), expected) << "input: " << input;
  }
}

